export const EMO = { defrost: '🥩', spa: '🛁', breakfast: '🍳', work: '💼', lunch: '🥗', 'workend-soon': '⏳', workend: '🌿', dress: '👗', dinner: '🍽️', bath: '🛁', joy: '🎨', proj1: '🧵', proj2: '🧵', save: '📝', clean: '🧹', review: '🗒️', bed: '🌙', screen: '📵', half: '🌙', chores: '🧺', walk: '🚶‍♀️', lessonprep: '📚', water: '💧', pay: '🐷' };
// День копилки: 15 число, а если оно выходное, то предыдущий рабочий день
export function payDay(ds) {
  const y = ds.slice(0, 4), m = ds.slice(5, 7);
  let d = `${y}-${m}-15`;
  const dw = dayOfWeek(d);
  if (dw === 6) d = addDays(d, -1); else if (dw === 7) d = addDays(d, -2);
  return d;
}
export function dayReminders(ds, cfg) {
  const dow = dayOfWeek(ds), w = weekNumber(ds, cfg.start);
  const B = bedtime(w, dow, cfg), weekend = dow >= 6;
  const quiet = weekend ? parseHM(cfg.quietWeekendUntil || '10:00') : 0; // выходным утром не беспокоим
  const list = buildDay(ds, cfg).filter((b) => b.remind).map((b) => ({ id: b.id, t: b.t + b.rOff, text: b.remind + (EMO[b.id] || EMO[b.id.replace(/\d+$/, '')] ? ' ' + (EMO[b.id] || EMO[b.id.replace(/\d+$/, '')]) : '') }));
  // вода раз в 2 часа в дневное время
  const W = weekend ? wakeWeekend(w, cfg) : parseHM(cfg.wake);
  for (let t = Math.max(W + 120, 9 * 60); t <= Math.min(B - 150, 20 * 60); t += (cfg.moreReminders !== false ? 90 : 120)) if (!list.some((r) => Math.abs(r.t - t) < 20)) list.push({ id: 'water-' + t, t, text: 'Стакан воды ' + EMO.water });
  // ver. 5.0: больше напоминаний (config.json: moreReminders false отключает)
  if (cfg.moreReminders !== false) {
    const more = [[W + 30, 'sv1', 'Утренний опрос: загляни в приложение, пара быстрых вопросов.'], [13 * 60 + 10, 'sv2', 'Дневной опрос: как силы, еда, вода? Две минуты в приложении.'], [17 * 60 + 40, 'sv3', 'Вечерний опрос: как прошёл день? Загляни в приложение.'], [B - 40, 'sv4', 'Опрос перед сном: пара вопросов и отбой.'],
      [11 * 60 + 30, 'mv1', 'Разомни шею и плечи 3 минуты, встань из-за стола.'], [weekend ? 15 * 60 + 30 : 15 * 60 + 40, 'mv2', 'Встань, пройдись, выпей воды. Так легче дотянуть до вечера без сна.'], [weekend ? 16 * 60 + 30 : 18 * 60 + 30, 'ev1', 'Вечернее окно: не ложись, сделай что-то на ногах. Если тянет, открой «Тянет в сон».']];
    for (const [t, id, text] of more) if (!list.some((r) => Math.abs(r.t - t) < 15)) list.push({ id, t, text });
  }
  // копилка
  if (payDay(ds) === ds) list.push({ id: 'pay', t: 12 * 60, text: 'Копилка: если хочешь, внеси сумму за месяц ' + EMO.pay });
  // после отбоя и рано утром не беспокоим
  return list.filter((r) => r.t <= B && r.t >= quiet).sort((a, b) => a.t - b.t);
}

// Что нужно отправить в окне (now-5, now] минут реального времени дня ds
export function dueReminders(ds, nowMin, cfg) {
  const res = [];
  for (const r of dayReminders(ds, cfg)) if (r.t > nowMin - 5 && r.t <= nowMin) res.push(r);
  for (const r of dayReminders(addDays(ds, -1), cfg)) {
    const t = r.t - 1440; // напоминания после полуночи вчерашнего дня
    if (t >= 0 && t > nowMin - 5 && t <= nowMin) res.push({ ...r, t });
  }
  return res;
}

// Напоминание о сроках годности: раз в день, по умолчанию в 9:00 (в выходные не раньше тихих часов).
export function expiryReminder(ds, nowMin, cfg, items) {
  const at = Math.max(parseHM(cfg.fridgeAt || '09:00'), dayOfWeek(ds) >= 6 ? parseHM(cfg.quietWeekendUntil || '10:00') : 0);
  if (!(at > nowMin - 5 && at <= nowMin)) return null;
  const say = (d) => (d < 0 ? 'просрочено' : d === 0 ? 'сегодня' : 'завтра');
  const soon = (items || []).filter((x) => x && x.exp && x.name).map((x) => ({ n: x.name, d: dayNum(x.exp) - dayNum(ds) })).filter((x) => x.d <= 1 && x.d >= -2).sort((a, b) => a.d - b.d);
  if (!soon.length) return null;
  return { id: 'fridge-' + ds, t: at, text: 'Скоро испортится: ' + soon.slice(0, 4).map((x) => x.n + ' (' + say(x.d) + ')').join(', ') + (soon.length > 4 ? ' и ещё ' + (soon.length - 4) : '') + '. Подсказать, что приготовить, можно в приложении.' };
}

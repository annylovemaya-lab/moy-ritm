export const parseHM = (s) => { const [h, m] = String(s).split(':').map(Number); return h * 60 + m; };
export const fmt = (min) => { min = ((Math.round(min) % 1440) + 1440) % 1440; return String(Math.floor(min / 60)).padStart(2, '0') + ':' + String(min % 60).padStart(2, '0'); };

// День недели: 1 = понедельник ... 7 = воскресенье
export const dayOfWeek = (ds) => { const x = new Date(ds + 'T12:00:00Z').getUTCDay(); return x === 0 ? 7 : x; };
const dayNum = (ds) => Math.floor(new Date(ds + 'T12:00:00Z').getTime() / 86400000);
export const addDays = (ds, n) => new Date((dayNum(ds) + n) * 86400000 + 43200000).toISOString().slice(0, 10);

// Неделя плана: от 1 до 12 (до старта считается первой, после 12-й остаётся 12-й)
export const weekNumber = (ds, start) => {
  const w = Math.floor((dayNum(ds) - dayNum(start)) / 7) + 1;
  return Math.min(12, Math.max(1, w));
};
export const daysToStart = (ds, start) => dayNum(start) - dayNum(ds);

const tier = (w) => (w <= 2 ? 0 : w <= 4 ? 1 : w <= 6 ? 2 : 3);
export const bedtime = (w, dow, cfg) => {
  let b = parseHM(cfg.bedtimes[tier(w)]);
  if (b < 12 * 60) b += 1440; // после полуночи
  if (dow === 5 || dow === 6) b += cfg.weekendBedExtra; // в ночь на субботу и воскресенье
  return b;
};
export const wakeWeekend = (w, cfg) => parseHM(cfg.wakeWeekend[w <= 2 ? 0 : w <= 4 ? 1 : 2]);

